export function ruleText(text: string, locale: Locale): string {
  if (locale !== "it") return text
  let match = /^Keep the (pattern|name) under (\d+) characters$/.exec(text)
  if (match) return `Mantieni ${match[1] === "pattern" ? "l’espressione" : "il nome"} entro ${match[2]} caratteri`
  match = /^A rule can have at most (\d+) (conditions|actions)$/.exec(text)
  if (match) return `Una regola può avere al massimo ${match[1]} ${match[2] === "conditions" ? "condizioni" : "azioni"}`
  match = /^Invalid regex: (.*)$/.exec(text)
  if (match) return `Espressione regolare non valida: ${match[1]}`
  match = /^Rule created — added the (.*) label$/.exec(text)
  if (match) return `Regola creata: aggiunta l’etichetta ${match[1]}`
  match = /^Label invoices and billing questions and assign them to (.*)\.$/.exec(text)
  if (match) return `Etichetta fatture e richieste di fatturazione e assegnale a ${match[1]}.`
  match = /^Spread emails sent to support@ evenly across a team\.$/.exec(text)
  if (match) return "Distribuisce in modo uniforme tra i membri del team le email inviate a support@."
  match = /^Needs a shared “(.*)” label — ask someone who can manage labels to create it\.$/.exec(text)
  if (match) return `Serve l’etichetta condivisa “${match[1]}”: chiedi a chi gestisce le etichette di crearla.`
  const duration = /^(\d+) (week|weeks|day|days|hour|hours|minute|minutes|time|times)$/.exec(text)
  if (duration) {
    const units: Record<string, string> = { week: "settimana", weeks: "settimane", day: "giorno", days: "giorni", hour: "ora", hours: "ore", minute: "minuto", minutes: "minuti", time: "volta", times: "volte" }
    const n = Number(duration[1])
    const unit = units[duration[2]!] ?? duration[2]!
    return `${n} ${unit}`
  }
  return italian[text] ?? text
}
